function formatPrice(priceCZK) {
  if (currentCurrency === 'EUR') {
    const eur = Math.round(priceCZK / EUR_RATE);
    return `${eur} €`;
  }
  return `${priceCZK.toLocaleString('cs-CZ')} Kč`;
}

