const EUR_RATE = 25;

let currentLang = localStorage.getItem('byelmarie_lang') || window.ShopifyLocale || 'cs';
if (currentLang !== 'cs' && currentLang !== 'en') {
  currentLang = 'cs';
}
let currentCurrency = window.ShopifyCurrency || localStorage.getItem('byelmarie_currency') || 'CZK';

function t(key) {
  return translations[currentLang][key] || key;
}

function formatPrice(priceCZK) {
  if (currentCurrency === 'EUR') {
    const eur = Math.round(priceCZK / EUR_RATE);
    return `${eur} €`;
  }
  return `${priceCZK.toLocaleString('cs-CZ')} Kč`;
}

const flags = {
  cs: `<svg viewBox="0 0 30 20" width="18" height="12" style="display: inline-block; vertical-align: middle; border: 1px solid var(--color-border);"><rect width="30" height="20" fill="#e3001a"/><path d="M0 0h30v10H0z" fill="#fff"/><path d="M0 0l15 10L0 20z" fill="#11457e"/></svg>`,
  en: `<svg viewBox="0 0 30 20" width="18" height="12" style="display: inline-block; vertical-align: middle; border: 1px solid var(--color-border);"><rect width="30" height="20" fill="#012169"/><path d="M0 0l30 20M30 0L0 20" stroke="#fff" stroke-width="3"/><path d="M0 0l30 20M30 0L0 20" stroke="#c8102e" stroke-width="2"/><path d="M15 0v20M0 10h30" stroke="#fff" stroke-width="5"/><path d="M15 0v20M0 10h30" stroke="#c8102e" stroke-width="3"/></svg>`
};

const currencySymbols = {
  CZK: 'Kč',
  EUR: '€'
};

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('byelmarie_lang', lang);
  applyTranslations();
  updateLangToggle();
  updateLocalizationSelector();
  updateLocDropdownHighlight();
}

function setCurrency(currency) {
  currentCurrency = currency;
  localStorage.setItem('byelmarie_currency', currency);
  updatePrices();
  updateCurrencyToggle();
  updateLocalizationSelector();
  updateLocDropdownHighlight();
  if (typeof renderCartPage === 'function') {
    renderCartPage();
  }
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[currentLang][key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = translations[currentLang][key];
      } else {
        el.innerHTML = translations[currentLang][key].replace(/\n/g, '<br>');
      }
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (translations[currentLang][key]) {
      el.placeholder = translations[currentLang][key];
    }
  });

  document.documentElement.lang = currentLang;
}

function updatePrices() {
  document.querySelectorAll('[data-price]').forEach(el => {
    const czk = parseInt(el.getAttribute('data-price'));
    el.textContent = formatPrice(czk);
  });
  document.querySelectorAll('[data-price-from]').forEach(el => {
    const czk = parseInt(el.getAttribute('data-price-from'));
    el.textContent = `${t('from')} ${formatPrice(czk)}`;
  });
}

function updateLangToggle() {
  document.querySelectorAll('.lang-option, .lang-opt').forEach(el => {
    el.classList.toggle('active', el.dataset.lang === currentLang);
  });
  const lbl = document.getElementById('lang-label');
  if (lbl) lbl.textContent = currentLang.toUpperCase();
}

function updateCurrencyToggle() {
  document.querySelectorAll('.currency-option').forEach(el => {
    el.classList.toggle('active', el.dataset.currency === currentCurrency);
  });
  const sym = document.getElementById('currency-symbol');
  const lbl = document.getElementById('currency-label');
  if (sym) sym.textContent = currentCurrency === 'EUR' ? '€' : 'Kč';
  if (lbl) lbl.textContent = currentCurrency;
  document.querySelectorAll('.currency-opt').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.currency === currentCurrency);
  });
}

function updateLocalizationSelector() {
  const toggle = document.getElementById('loc-toggle');
  if (toggle) {
    const flagEl = toggle.querySelector('.loc-toggle__flag');
    const currEl = toggle.querySelector('.loc-toggle__currency');
    if (flagEl) flagEl.innerHTML = flags[currentLang];
    if (currEl) currEl.textContent = currencySymbols[currentCurrency];
  }
}

function initLocOptions() {
  document.querySelectorAll('.loc-opt').forEach(btn => {

    const flagEl = btn.querySelector('.loc-opt__flag');
    const lang = btn.dataset.lang;
    if (flagEl && !flagEl.innerHTML && flags[lang]) {
      flagEl.innerHTML = flags[lang];
    }

    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const lang = btn.dataset.lang;
      const currency = btn.dataset.currency;
      setLang(lang);
      setCurrency(currency);

      setTimeout(() => {
        document.querySelector('.loc-dropdown-wrap')?.classList.remove('open');
      }, 250);
    });
  });
  updateLocDropdownHighlight();
}

function updateLocDropdownHighlight() {
  document.querySelectorAll('.loc-opt').forEach(btn => {
    const isActive = btn.dataset.lang === currentLang && btn.dataset.currency === currentCurrency;
    btn.classList.toggle('active', isActive);
  });
}

function initI18n() {
  applyTranslations();
  updatePrices();
  updateLangToggle();
  updateCurrencyToggle();
  updateLocalizationSelector();
  initLocOptions();
}

document.addEventListener('DOMContentLoaded', initI18n);
